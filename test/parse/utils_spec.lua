local utils = require('treetags.parse.utils')

describe('treetags.parse.utils', function()
    it('__get_commit_hash - happy', function()
        local commit_hash = utils.__get_commit_hash()
        assert(commit_hash ~= '')
        assert(commit_hash ~= nil)
    end)

    it('__get_commit_hash - can be called multiple times', function()
        local first = utils.__get_commit_hash()
        utils.__get_commit_hash()
        utils.__get_commit_hash()
        utils.__get_commit_hash()
        utils.__get_commit_hash()
        local last = utils.__get_commit_hash()
        assert(first == last)
    end)
end)
