local utils = require('treetags.parse.utils')
local first_commit = '49139a0'
local second_commit = '2722470'

describe('treetags.parse.utils', function()
    it('__has_extension', function()
        assert(utils.__has_extension('my/file.txt', nil))
        assert(utils.__has_extension('my/file.txt', {}))
        assert(utils.__has_extension('my/file.txt', { 'txt' }))
        assert(utils.__has_extension('my/file.txt', { 'md', 'txt' }))
        assert(not utils.__has_extension('my/file.wav', { 'md', 'txt' }))
    end)

    it('__get_commit_hash - happy', function()
        local commit_hash = utils.__get_commit_hash()
        assert(commit_hash ~= '')
        assert(commit_hash ~= nil)
    end)

    it('__get_commit_hash - can be called multiple times', function()
        local first = utils.__get_commit_hash()
        utils.__get_commit_hash()
        utils.__get_commit_hash()
        utils.__get_commit_hash()
        utils.__get_commit_hash()
        local last = utils.__get_commit_hash()
        assert(first == last)
    end)

    it('__get_changed_files -- non existing commits', function()
        local files = utils.__get_changed_files('blabla', 'dudu')
        assert(#files == 0)
    end)

    it('__get_changed_files -- swap start and end', function()
        local files1 = utils.__get_changed_files(first_commit, second_commit)
        local files2 = utils.__get_changed_files(second_commit, first_commit)
        assert(#files1 == #files2)
        assert(files1[1] == files2[1])
        assert(files1[2] == files2[2])
    end)

    it('__get_changed_files -- no files changed (with diff-filter)', function()
        -- I know that there weren't deletions
        local files = utils.__get_changed_files(first_commit, second_commit, 'D')
        assert(#files == 0)
    end)

    it('__get_changed_files -- all files', function()
        local files = utils.__get_changed_files(first_commit, second_commit)
        assert(files[1] == '.github/workflows/ci.yml')
        assert(files[2] == '.github/workflows/lint.yml')
        assert(files[3] == 'Makefile')
        assert(files[4] == 'README.md')
        assert(files[5] == 'doc/treetags.txt')
        assert(files[6] == 'lua/treetags/database/buffer.lua')
        assert(files[7] == 'lua/treetags/database/init.lua')
        assert(files[8] == 'lua/treetags/database/query.lua')
        assert(files[9] == 'lua/treetags/database/utils.lua')
        assert(files[10] == 'lua/treetags/health.lua')
        assert(files[11] == 'lua/treetags/init.lua')
        assert(files[12] == 'lua/treetags/main/init.lua')
        assert(files[13] == 'lua/treetags/main/utils.lua')
        assert(files[14] == 'lua/treetags/parse/init.lua')
        assert(files[15] == 'lua/treetags/pickers/fzf/builder.lua')
        assert(files[16] == 'lua/treetags/pickers/fzf/init.lua')
        assert(files[17] == 'lua/treetags/pickers/telescope/builder.lua')
        assert(files[18] == 'lua/treetags/pickers/telescope/init.lua')
        assert(files[19] == 'lua/treetags/pickers/utils.lua')
        assert(files[20] == 'scripts/minimal_init.lua')
        assert(files[21] == 'test/database/buffer_spec.lua')
        assert(files[22] == 'test/database/database_spec.lua')
        assert(files[23] == 'test/database/query_spec.lua')
        assert(files[24] == 'test/database/utils_spec.lua')
        assert(files[25] == 'test/main/init_database_spec.lua')
        assert(files[26] == 'test/main/main_spec.lua')
        assert(files[27] == 'test/main/utils_spec.lua')
        assert(files[28] == 'test/parse/parse_file_spec.lua')
        assert(files[29] == 'test/parse/parse_spec.lua')
        assert(files[30] == 'test/sources/definition.cs')
        assert(files[31] == 'test/sources/definition.js')
        assert(files[32] == 'test/sources/definition.lua')
        assert(files[33] == 'test/treetags/treetags_spec.lua')
    end)

    it('__get_changed_files -- txt and md files', function()
        local files = utils.__get_changed_files(first_commit, second_commit, nil, { 'md', 'txt' })
        assert(#files == 2)
        assert(files[1] == 'README.md')
        assert(files[2] == 'doc/treetags.txt')
    end)
end)
